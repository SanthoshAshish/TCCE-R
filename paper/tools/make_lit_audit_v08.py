"""Generate revision/literature/LITERATURE_AUDIT_v08.md from the cited-reference list, the Crossref verification records and the
manuscript (where each reference is cited).   python paper/tools/make_lit_audit_v08.py   (run after build_manuscript_v08.py)"""
import html
import json
import os
import re

MS = "paper/manuscript_v0.8.md"
OUT = "revision/literature/LITERATURE_AUDIT_v08.md"
TOPIC = {
    "adaptive / event-triggered consensus": ["Zhang2023", "Xiao2022", "Wang2023", "PerezSalesa2023", "Kim2023", "Wang2024", "Dong2026", "Tian2022"],
    "time-varying topology and link failures": ["Battilotti2024", "Liu2024", "Li2024", "Yan2024", "Fu2026", "Gao2024", "Han2025"],
    "connectivity-aware topology control / rewiring": ["Muthirayan2022", "Chujyo2024", "Wang2023b", "Shan2025", "Feng2024", "Shi2025", "Shetty2023", "ElHamamsy2023", "Du2025", "Estrada2026"],
    "resilience and recovery": ["Imteaj2023", "Jo2024", "Jimenez2023", "AndresThio2022", "Li2022", "Awoyemi2022", "Hafaiedh2022"],
    "predictive / learning / change-detection": ["Zhang2023b", "Mei2024", "Tang2025", "Binh2026", "ElHamamsy2023", "Du2025", "Han2025"],
    "mutation / rewiring budgets": ["Chujyo2024", "Muthirayan2022"],
    "foundations and statistics": ["Fiedler1973", "XiaoBoyd2004", "OlfatiSaberMurray2004", "GhoshBoyd2006", "Page1954", "Wilcoxon1945", "Holm1979", "Efron1979", "Lakens2017"],
}
FLAG = {"Holm1979": "No DOI found (not in Crossref; the guessed DOIs 10.2307/4615733 and a Wiley-style DOI return 404). Scand. J. Statist. 6(2):65-70 and JSTOR stable/4615733 confirmed by web sources on 2026-11-04 (search results quoting the JSTOR record), not by the original. No DOI is given in the reference.",
        "Wilcoxon1945": "Crossref confirms DOI 10.2307/3001968, Biometrics Bulletin 1(6):80 (Dec 1945). Web sources (a 1992 historical chapter by Noether in Breakthroughs in Statistics; encyclopaedic pages) state that this paper introduced both the signed-rank and the rank-sum tests; the original was not re-read.",
        "GhoshBoyd2006": "Full text read in an earlier project step (`docs/KEY_PAPERS_VERIFICATION.md`): the first-order gain used by the code is eq. (7).",
        "Dong2026": "2026 record without volume/pages in Crossref at retrieval; existence and title verified only.",
        "Estrada2026": "2026 record (pages '1-1' in Crossref); existence and title verified only.",
        "Fu2026": "2026 record; existence, title and year verified only.",
        "Binh2026": "2026 record; existence, title and year verified only."}


def main():
    text = open(MS, encoding="utf-8").read()
    cited = json.load(open("paper/references/refs_v08_cited.json"))["cited"]
    recent = {e["slug"]: e for e in json.load(open("paper/references/refs_v08_recent_final.json", encoding="utf-8"))}
    old = json.load(open("paper/references/references_verified.json", encoding="utf-8"))
    where = {i: [] for i in range(1, len(cited) + 1)}
    head = ""
    for line in text.split("## References")[0].split("\n"):
        if line.startswith("#"):
            head = re.match(r"#+ ((?:\d+(?:\.\d+)*)|Abstract|Appendix \w)?", line).group(1) or line.strip("# ")[:12]
        for g in re.findall(r"\[(\d+(?:, \d+)*)\]", line):
            if g.split(", ") == ["0", "1"]:
                continue
            for n in g.split(", "):
                if int(n) in where and head not in where[int(n)]:
                    where[int(n)].append(head)
    rows = []
    for i, slug in enumerate(cited, 1):
        topics = "; ".join(t for t, v in TOPIC.items() if slug in v)
        if slug in recent:
            e = recent[slug]
            rows.append(f"| {i} | {slug} | {e['crossref_year']} | {topics} | {e['doi']} | Crossref record found; title and year match (`refs_v08_verification.json`) | titles/metadata only | {', '.join(where[i])} | {FLAG.get(slug, '')} |")
        else:
            o = old[slug]
            ver = "Crossref record matches the DOI (earlier project step, `references_verified.json`)" if o.get("doi") else "**not verified**"
            rows.append(f"| {i} | {slug} | {o['year']} | {topics} | {o.get('doi') or 'none'} | {ver} | metadata; see flag | {', '.join(where[i])} | {FLAG.get(slug, '')} |")
    n_recent = sum(1 for s in cited if s in recent)
    dropped = [k for k in old if k not in cited]
    md = ["# Literature audit for the v0.8 manuscript", "",
          f"Generated by `paper/tools/make_lit_audit_v08.py` from `paper/manuscript_v0.8.md`. **{len(cited)} references are cited; {n_recent} ({100 * n_recent / len(cited):.1f}%) are from 2022-2026.**",
          "", "## What was and was not verified", "",
          "- **Existence and bibliographic metadata (DOI, title, year, venue, authors)** of every recent reference was checked against the live Crossref API by `paper/tools/verify_refs_v08.py` (record in `paper/references/refs_v08_verification.json` and `refs_v08_added_verification.json`, retrieval date inside). All 36 recent entries matched.",
          "- **Claim support was checked only at the level of titles and metadata.** Abstracts and full texts of the 36 recent papers were **not** read for this revision; the manuscript therefore uses them only for descriptive statements about what kind of problem a paper addresses (as its title states) and never attributes a numerical or comparative result to them. A reviewer should confirm each statement against the paper before submission.",
          "- The nine foundational references were verified in earlier project steps (Crossref for eight; Holm (1979) is **not** verified by DOI).",
          "- The previously verified 2003-2017 references that are no longer cited are listed at the end; they remain in `references_verified.json`.",
          "- The 2022-2026 list originated from `refs_v2_recent.json` (34 entries of unknown provenance and no verification status when this revision began) plus two entries found by a Crossref topic search in this revision (Estrada 2026, Han 2025). Provenance of the original 34 is not documented; they are retained only because Crossref confirms them.",
          "", "## Coverage by the professor's topics (counts of cited references)", ""]
    for t, v in TOPIC.items():
        md.append(f"- {t}: {len([s for s in v if s in cited])}")
    md += ["", "Gaps: no relevant reference on **counterfactual / off-policy evaluation of topology control** was surfaced by a *brief, non-exhaustive* Crossref keyword search (six queries; results were unrelated policy-evaluation papers); this is a limit of our search, **not evidence that no such literature exists**, and the gap is unverified. The counterfactual feedback is therefore described as a model-based replay without a supporting citation; **mutation-budget** coverage is thin (two references).",
           "", "## Reference table", "", "| # | slug | year | topic(s) | DOI | verification | claim support checked | cited in sections | flags |", "|---|---|---|---|---|---|---|---|---|"] + rows
    md += ["", "## Previously verified references no longer cited", "", ", ".join(dropped), "",
           "They were dropped to keep the reference list focused and to meet the recency target (>= 80% from 2022-2026 with the sources that could be verified); the target is met only exactly (80.0%), so adding any older reference would break it."]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
